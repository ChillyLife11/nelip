// Направление анимации перехода между экранами.
//
// По умолчанию его определяет позиция в истории: уменьшилась — значит назад.
// Но кнопка «Назад» в шапке уходит не через history.back(), а через push с
// явным адресом (на экран можно попасть из разных мест, и шаг назад по истории
// увёл бы не туда). Позиция при этом растёт, и переход выглядел бы как движение
// вперёд — поэтому такие переходы помечаем здесь.
let backIntent = false

export function markBack() {
	backIntent = true
}

// Забирает пометку разово: следующий переход снова считается обычным.
export function takeBackIntent() {
	const marked = backIntent
	backIntent = false
	return marked
}
